#!/usr/bin/env node
/**
 * Generates the Argon2id key derivation defaults for every non-TypeScript client.
 *
 * Input: core/models/src/defaults/EncryptionDefaults.ts
 * Outputs:
 *   - core/rust/src/argon2/defaults.rs (Rust core)
 *   - apps/server/Utilities/Cryptography/AliasVault.Cryptography.Client/Argon2Defaults.cs
 *   - apps/mobile-app/android/app/src/androidTest/java/net/aliasvault/app/EncryptionDefaults.kt
 *   - apps/mobile-app/ios/AliasVaultUITests/EncryptionDefaults.swift
 *
 * Note: TypeScript clients import the constants directly from `@/utils/dist/core/models/defaults`.
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.join(__dirname, '../../..');
const TS_SOURCE = path.join(REPO_ROOT, 'core/models/src/defaults/EncryptionDefaults.ts');
const TS_SOURCE_REL = 'core/models/src/defaults/EncryptionDefaults.ts';

const RUST_OUTPUT = path.join(REPO_ROOT, 'core/rust/src/argon2/defaults.rs');
const CS_OUTPUT = path.join(
  REPO_ROOT,
  'apps/server/Utilities/Cryptography/AliasVault.Cryptography.Client/Argon2Defaults.cs',
);
const KOTLIN_OUTPUT = path.join(
  REPO_ROOT,
  'apps/mobile-app/android/app/src/androidTest/java/net/aliasvault/app/EncryptionDefaults.kt',
);
const SWIFT_OUTPUT = path.join(REPO_ROOT, 'apps/mobile-app/ios/AliasVaultUITests/EncryptionDefaults.swift');

/** Names the generator requires; a partial parse must not produce output. */
const REQUIRED_NUMBERS = ['ARGON2ID_DEGREE_OF_PARALLELISM', 'ARGON2ID_MEMORY_SIZE', 'ARGON2ID_ITERATIONS'];
const REQUIRED_STRINGS = ['ENCRYPTION_TYPE'];

/**
 * Parse `export const NAME = 123;` and `export const NAME = 'text';` out of the source,
 * each with its leading single-line JSDoc comment, preserving order.
 */
function parseConstants(source) {
  const constants = [];
  const lines = source.split('\n');
  let pendingDoc = null;

  for (const line of lines) {
    const trimmed = line.trim();

    if (trimmed.startsWith('/**') && trimmed.endsWith('*/')) {
      pendingDoc = trimmed.slice(3, -2).trim();
      continue;
    }

    const numberMatch = line.match(/^\s*export const ([A-Z0-9_]+)\s*=\s*(\d+)\s*;/);
    if (numberMatch) {
      constants.push({ name: numberMatch[1], value: Number(numberMatch[2]), kind: 'number', doc: pendingDoc || `${numberMatch[1]}.` });
      pendingDoc = null;
      continue;
    }

    const stringMatch = line.match(/^\s*export const ([A-Z0-9_]+)\s*=\s*'([^']*)'\s*;/);
    if (stringMatch) {
      constants.push({ name: stringMatch[1], value: stringMatch[2], kind: 'string', doc: pendingDoc || `${stringMatch[1]}.` });
      pendingDoc = null;
      continue;
    }

    if (trimmed !== '') {
      pendingDoc = null;
    }
  }

  const found = new Set(constants.map((c) => c.name));
  const missing = [...REQUIRED_NUMBERS, ...REQUIRED_STRINGS].filter((name) => !found.has(name));
  if (missing.length > 0) {
    // Emitting a partial set would hand some client a parameter the others never used,
    // which produces a vault only that client can open.
    throw new Error(`${TS_SOURCE_REL} is missing: ${missing.join(', ')}`);
  }

  return constants;
}

/** Look a parsed constant up by name. */
function valueOf(constants, name) {
  return constants.find((c) => c.name === name).value;
}

/**
 * Build the settings string in the canonical key order. This order is also written out
 * in the TypeScript source; the .NET consistency test asserts the two agree.
 */
function buildSettings(constants) {
  return JSON.stringify({
    DegreeOfParallelism: valueOf(constants, 'ARGON2ID_DEGREE_OF_PARALLELISM'),
    MemorySize: valueOf(constants, 'ARGON2ID_MEMORY_SIZE'),
    Iterations: valueOf(constants, 'ARGON2ID_ITERATIONS'),
  });
}

/** SCREAMING_SNAKE_CASE -> PascalCase (ARGON2ID_MEMORY_SIZE -> Argon2idMemorySize). */
function toPascalCase(name) {
  return name
    .toLowerCase()
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

/** PascalCase -> camelCase. */
function toCamelCase(name) {
  const pascal = toPascalCase(name);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

/** The settings entry is derived rather than parsed, so every emitter appends it the same way. */
function withSettings(constants, settings) {
  return [
    ...constants,
    {
      name: 'ENCRYPTION_SETTINGS',
      value: settings,
      kind: 'string',
      doc: 'The settings exactly as they are stored against a vault. Key order is part of the value.',
    },
  ];
}

function generateRust(entries) {
  const header = `//! Argon2id key derivation defaults shared by every AliasVault client.
//!
//! @generated — do NOT edit this file directly. It is generated from
//! ${TS_SOURCE_REL} by core/models/scripts/generate-encryption-defaults.cjs.
//! Edit the TypeScript source and run 'core/models/build.sh' to regenerate.
`;

  const body = entries
    .map((c) =>
      c.kind === 'number'
        ? `/// ${c.doc}\npub const ${c.name}: u32 = ${c.value};`
        : `/// ${c.doc}\npub const ${c.name}: &str = ${JSON.stringify(c.value)};`,
    )
    .join('\n\n');

  return `${header}\n${body}\n`;
}

function generateCSharp(entries) {
  const header = `// <auto-generated />
// This file is auto-generated from ${TS_SOURCE_REL}
// Do not edit this file directly. Run 'core/models/build.sh' (or
// 'node core/models/scripts/generate-encryption-defaults.cjs') to regenerate.

#nullable enable

namespace AliasVault.Cryptography.Client;

/// <summary>
/// Argon2id key derivation defaults shared across all AliasVault clients.
/// </summary>
public static class Argon2Defaults
{`;

  const body = entries
    .map((c) => {
      const csName = toPascalCase(c.name);
      const declaration =
        c.kind === 'number'
          ? `    public const int ${csName} = ${c.value};`
          : `    public const string ${csName} = ${JSON.stringify(c.value)};`;
      return `    /// <summary>\n    /// ${c.doc}\n    /// </summary>\n${declaration}`;
    })
    .join('\n\n');

  return `${header}\n${body}\n}\n`;
}

function generateKotlin(entries) {
  const header = `// @generated — do NOT edit this file directly. It is generated from
// ${TS_SOURCE_REL} by core/models/scripts/generate-encryption-defaults.cjs.
// Edit the TypeScript source and run 'core/models/build.sh' to regenerate.

package net.aliasvault.app

/**
 * Argon2id key derivation defaults shared across all AliasVault clients.
 */
object EncryptionDefaults {`;

  const body = entries
    .map((c) => {
      const declaration =
        c.kind === 'number'
          ? `    const val ${c.name} = ${c.value}`
          : `    const val ${c.name} = ${JSON.stringify(c.value)}`;
      return `    /** ${c.doc} */\n${declaration}`;
    })
    .join('\n\n');

  return `${header}\n${body}\n}\n`;
}

function generateSwift(entries) {
  const header = `// @generated — do NOT edit this file directly. It is generated from
// ${TS_SOURCE_REL} by core/models/scripts/generate-encryption-defaults.cjs.
// Edit the TypeScript source and run 'core/models/build.sh' to regenerate.

import Foundation

/// Argon2id key derivation defaults shared across all AliasVault clients.
enum EncryptionDefaults {`;

  const body = entries
    .map((c) => {
      const swiftName = toCamelCase(c.name);
      const declaration =
        c.kind === 'number'
          ? `    static let ${swiftName}: UInt32 = ${c.value}`
          : `    static let ${swiftName}: String = ${JSON.stringify(c.value)}`;
      return `    /// ${c.doc}\n${declaration}`;
    })
    .join('\n\n');

  return `${header}\n${body}\n}\n`;
}

function writeIfChanged(filePath, contents) {
  const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (existing === contents) {
    console.log(`  ✓ up to date: ${path.relative(REPO_ROOT, filePath)}`);
    return;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
  console.log(`  ✎ wrote:      ${path.relative(REPO_ROOT, filePath)}`);
}

function main() {
  const source = fs.readFileSync(TS_SOURCE, 'utf8');
  const constants = parseConstants(source);
  const settings = buildSettings(constants);
  const entries = withSettings(constants, settings);

  console.log(`Generating encryption defaults from ${TS_SOURCE_REL}:`);
  console.log(`  ${settings}`);

  writeIfChanged(RUST_OUTPUT, generateRust(entries));
  writeIfChanged(CS_OUTPUT, generateCSharp(entries));
  writeIfChanged(KOTLIN_OUTPUT, generateKotlin(entries));
  writeIfChanged(SWIFT_OUTPUT, generateSwift(entries));
}

main();
